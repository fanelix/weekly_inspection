import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
mkdirSync('dist',{recursive:true});
const backend=['Config','Schema','Validation','Auth','Storage','Code'];
writeFileSync('dist/Code.gs','// Generated by npm run bundle; edit appsscript/ sources instead.\n'+backend.map(name=>'\n// ----- '+name+'.gs -----\n'+readFileSync('appsscript/'+name+'.gs','utf8')).join('\n'));
const html=readFileSync('appsscript/Index.html','utf8').replace(/<\?!= include_\('([A-Za-z]+)'\); \?>/g,(_,name)=>readFileSync('appsscript/'+name+'.html','utf8'));
writeFileSync('dist/Index.html',html);
writeFileSync('dist/appsscript.json',readFileSync('appsscript/appsscript.json','utf8'));
console.log('Deployment bundle: dist/Code.gs, dist/Index.html, dist/appsscript.json');
